    #region Parsing Helpers

    /// <summary>
    /// Encodes a mail header value using RFC 2047 base64 encoding when it contains
    /// non-ASCII characters (e.g. em dashes, accented letters, emoji).
    /// Pure-ASCII values are returned unchanged.
    /// </summary>
    private static string EncodeMailHeaderValue(string value)
    {
        if (value.All(c => c < 128))
            return value;
        var encoded = Convert.ToBase64String(Encoding.UTF8.GetBytes(value));
        return $"=?utf-8?B?{encoded}?=";
    }

    private static string GetHeader(List<GmailHeader> headers, string name)
    {
        return headers.FirstOrDefault(h =>
            h.Name.Equals(name, StringComparison.OrdinalIgnoreCase))?.Value ?? "";
    }

    private static (string Email, string? Name) ParseEmailAddress(string fromHeader)
    {
        if (string.IsNullOrWhiteSpace(fromHeader))
            return ("unknown@unknown.com", null);

        // Format: "Display Name <email@domain.com>" or "email@domain.com"
        var match = Regex.Match(fromHeader, @"(?:""?(.+?)""?\s*)?<(.+?)>");
        if (match.Success)
        {
            return (match.Groups[2].Value.Trim(), match.Groups[1].Value.Trim());
        }

        // Plain email
        var emailMatch = Regex.Match(fromHeader, @"[\w.+-]+@[\w.-]+\.\w+");
        return emailMatch.Success ? (emailMatch.Value, null) : (fromHeader.Trim(), null);
    }

    private static string CleanSubject(string subject)
    {
        // Remove Re:, Fwd:, Fw:, [#SS-XXXXX], etc.
        var cleaned = Regex.Replace(subject, @"^(Re:\s*|Fwd?:\s*)+", "", RegexOptions.IgnoreCase).Trim();
        cleaned = TicketRefRegex.Replace(cleaned, "").Trim();
        return cleaned;
    }

    private static bool IsAutoReply(List<GmailHeader> headers, string fromEmail)
    {
        // Check for auto-reply indicators
        var autoSubmitted = GetHeader(headers, "Auto-Submitted");
        if (!string.IsNullOrEmpty(autoSubmitted) && autoSubmitted != "no")
            return true;

        var precedence = GetHeader(headers, "Precedence");
        if (precedence.Equals("bulk", StringComparison.OrdinalIgnoreCase) ||
            precedence.Equals("junk", StringComparison.OrdinalIgnoreCase))
            return true;

        // Common no-reply addresses
        if (fromEmail.Contains("noreply", StringComparison.OrdinalIgnoreCase) ||
            fromEmail.Contains("no-reply", StringComparison.OrdinalIgnoreCase) ||
            fromEmail.Contains("mailer-daemon", StringComparison.OrdinalIgnoreCase) ||
            fromEmail.Contains("postmaster", StringComparison.OrdinalIgnoreCase))
            return true;

        return false;
    }

    /// <summary>Returns plain-text body for storage/search (stored in Description).</summary>
    private static string ExtractPlainBody(GmailFullMessage message)
    {
        var textBody = ExtractPartBody(message.Payload, "text/plain");
        if (!string.IsNullOrWhiteSpace(textBody))
            return textBody.Trim();

        // Fall back: strip HTML tags so Description always has readable text
        var htmlBody = ExtractPartBody(message.Payload, "text/html");
        if (!string.IsNullOrWhiteSpace(htmlBody))
        {
            var sanitizer = new HtmlSanitizer();
            var sanitized = sanitizer.Sanitize(htmlBody);
            return Regex.Replace(sanitized, "<[^>]+>", " ").Trim();
        }

        return "(No content)";
    }

    /// <summary>
    /// Returns sanitized HTML body for rich display (stored in DescriptionHtml).
    /// Returns null when only plain text is available.
    /// </summary>
    private static string? ExtractHtmlBody(GmailFullMessage message)
    {
        var htmlBody = ExtractPartBody(message.Payload, "text/html");
        if (string.IsNullOrWhiteSpace(htmlBody)) return null;

        var sanitizer = new HtmlSanitizer();
        // Allow safe styling attributes used by email clients
        sanitizer.AllowedAttributes.Add("style");
        sanitizer.AllowedAttributes.Add("align");
        sanitizer.AllowedAttributes.Add("width");
        sanitizer.AllowedAttributes.Add("height");
        sanitizer.AllowedAttributes.Add("cellpadding");
        sanitizer.AllowedAttributes.Add("cellspacing");
        sanitizer.AllowedAttributes.Add("border");
        sanitizer.AllowedAttributes.Add("bgcolor");
        sanitizer.AllowedTags.Add("table");
        sanitizer.AllowedTags.Add("thead");
        sanitizer.AllowedTags.Add("tbody");
        sanitizer.AllowedTags.Add("tr");
        sanitizer.AllowedTags.Add("td");
        sanitizer.AllowedTags.Add("th");
        sanitizer.AllowedTags.Add("img");
        sanitizer.AllowedAttributes.Add("src");
        sanitizer.AllowedAttributes.Add("alt");
        return sanitizer.Sanitize(htmlBody);
    }

    private static string? ExtractPartBody(GmailMessagePart? part, string mimeType)
    {
        if (part == null) return null;

        if (part.MimeType == mimeType && part.Body?.Data != null)
        {
            return DecodeBase64Url(part.Body.Data);
        }

        if (part.Parts != null)
        {
            foreach (var subPart in part.Parts)
            {
                var result = ExtractPartBody(subPart, mimeType);
                if (result != null) return result;
            }
        }

        return null;
    }

    private static string DecodeBase64Url(string base64Url)
    {
        var base64 = base64Url.Replace('-', '+').Replace('_', '/');
        var padLength = (4 - base64.Length % 4) % 4;
        base64 += new string('=', padLength);
        var bytes = Convert.FromBase64String(base64);
        return Encoding.UTF8.GetString(bytes);
    }

